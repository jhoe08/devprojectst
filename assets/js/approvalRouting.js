export function showConfirmationAlert(options) {
    const {
        title = "Are you sure?",
        text = "Click ‘Confirm’ to proceed.",
        confirmText = "Confirm",
        cancelText = "Cancel",
        icon = "warning",
        requestUrl,
        requestMethod = "POST",
        requestData = {},
        successTitle = "Success",
        successText = "Your request was processed successfully.",
        errorTitle = "Error",
        errorText = "Something went wrong.",
    } = options;

    swal({
        title,
        text,
        icon,
        buttons: {
            confirm: {
                text: confirmText,
                className: "btn btn-success",
            },
            cancel: {
                text: cancelText,
                visible: true,
                className: "btn btn-danger",
            },
        },
    }).then((confirmed) => {
        if (confirmed) {
            $.ajax({
                url: requestUrl,
                method: requestMethod,
                data: requestData,
                success: function (response) {
                    swal({
                        title: successTitle,
                        text: successText,
                        icon: "success",
                        buttons: {
                            confirm: {
                                className: "btn btn-success",
                            },
                        },
                    });
                    setTimeout(() => {
                        location.reload();
                    }, 1500);
                },
                error: function (xhr, status, error) {
                    swal({
                        title: errorTitle,
                        text: errorText,
                        icon: "error",
                        buttons: {
                            confirm: {
                                className: "btn btn-danger",
                            },
                        },
                    });
                }
            });
        } else {
            swal.close();
        }
    });
}

export function initApprovalRouting() {
    console.log('Approval routing initialized');
    // Get the card element that holds transaction data
    const transactionCard = document.querySelector('.card[data-current-transactions]');

    if (!transactionCard) return
    // Parse the JSON data stored in the dataset
    const transactionData = JSON.parse(transactionCard?.dataset.currentTransactions);

    // Destructure the approved budget from the parsed data
    const { approved_budget: approvedBudget } = transactionData;

    // Decide which message set to use based on the budget threshold
    const messageSet = parseFloat(approvedBudget) > 200_000
        ? publicBiddingMessages
        : smallValueMessages;

    // console.log(messageSet);


    $(document).on("click", ".alert_confirm", function (e) {
        e.preventDefault()
        const productId = $(this).data('product-id')
        const currentStep = $(this).data('step')
        const updatedBy = $('#created_by').val()



        if ([6, 7, 8].includes(currentStep)) {
            // const suppliers = document.getElementById(`suppliers_step`).value;
            // console.log({productId, currentStep, updatedBy})
        }

        showConfirmationAlert({
            title: messageSet[currentStep].initial.title,
            text: messageSet[currentStep].initial.text,
            requestUrl: "/approve",
            requestMethod: "POST",
            requestData: {
                product_id: productId,
                steps_number: currentStep,
                updated_by: updatedBy,
                remarks: messageSet[currentStep].confirmed.text
            },
            successTitle: messageSet[currentStep].confirmed.title,
            successText: messageSet[currentStep].confirmed.text,
        })
    })

    $(document).on("click", ".alert_deny", function (e) {
        const productId = $(this).data('product-id')
        const currentStep = $(this).data('step')
        showConfirmationAlert({
            title: messageSet[currentStep].denied.title,
            text: messageSet[currentStep].denied.text,
            requestUrl: "/disapprove",
            requestMethod: "POST",
            requestData: {
                //const { trans_id, steps_number, updated_by } = req.body;
                product_id: productId,
                steps_number: currentStep,
                remarks: messageSet[currentStep].confirmedDenied.text,
            },
            successTitle: messageSet[currentStep].confirmedDenied.title,
            successText: messageSet[currentStep].confirmedDenied.text,
        })
    })
}

function getMessages(budget, currentStep) {
    if (parseFloat(budget) > 200_000) {
        return publicBiddingMessages[currentStep].initial.title;
    }
    return smallValueMessages[currentStep].initial.title;
}
window.getProcurementMessages = getMessages;
window.publicBiddingMessages = publicBiddingMessages;
window.smallValueMessages = smallValueMessages;

if (typeof window !== "undefined") {
    initApprovalRouting();
}
